/* Little House Flower Studio: API bridge for the Studio's GitHub Pages address. Responses are never cached.
   Generated by scripts/build-studio-pages.mjs. Photographs stay on the website's address. */
const BASE='__BASE__/',WEBSITE='__WEBSITE__';
const API_PREFIX=BASE+'api/';
const BACKEND=['localhost','127.0.0.1','[::1]'].includes(self.location.hostname)
  ?'http://127.0.0.1:5580'
  :'https://little-house-flower-client-demo.sugary-crab-4853.chatgpt.site';
const DB_NAME='lhf-pages-access-v1:'+BASE;
const TOKEN_HEADERS={demo:'X-LHF-Demo-Session',customer:'X-LHF-Customer-Session',staff:'X-LHF-Staff-Session'};
let opening;
function database(){
  if(!opening)opening=new Promise((resolve,reject)=>{
    const request=indexedDB.open(DB_NAME,1);
    request.onupgradeneeded=()=>{if(!request.result.objectStoreNames.contains('access'))request.result.createObjectStore('access');};
    request.onsuccess=()=>{const db=request.result;db.onversionchange=()=>{db.close();opening=null;};resolve(db);};
    request.onerror=()=>{opening=null;reject(request.error);};
    request.onblocked=()=>{opening=null;reject(new Error('Browser storage is busy'));};
  });
  return opening;
}
async function readTokens(){
  const db=await database();
  return new Promise((resolve,reject)=>{const request=db.transaction('access','readonly').objectStore('access').get('tokens');request.onsuccess=()=>resolve(request.result||{});request.onerror=()=>reject(request.error);});
}
async function updateTokens(headers,sentDemo,{clear=false}={}){
  const changes={};for(const [key,header] of Object.entries(TOKEN_HEADERS))if(headers.has(header))changes[key]=headers.get(header)||'';
  if(!clear&&!Object.keys(changes).length)return;
  const db=await database();
  await new Promise((resolve,reject)=>{
    const transaction=db.transaction('access','readwrite'),store=transaction.objectStore('access'),request=store.get('tokens');
    request.onsuccess=()=>{
      const current=request.result||{};
      // An older request must not overwrite credentials returned by a password change.
      if((current.demo||'')!==(sentDemo||''))return;
      const next=clear?{}:{...current};
      for(const [key,value] of Object.entries(changes)){if(value)next[key]=value;else delete next[key];}
      store.put(next,'tokens');
    };
    transaction.oncomplete=()=>resolve();transaction.onerror=()=>reject(transaction.error);transaction.onabort=()=>reject(transaction.error||new Error('Browser storage is unavailable'));
  });
}
function sitePaths(value){
  if(typeof value==='string'){
    if(/^\/api\/[^\s]*$/.test(value))return BASE.slice(0,-1)+value;
    if(/^\/(?:img|media)\/[^\s]*$/.test(value))return WEBSITE+value;
    if(/^img\/[^\s]*$/.test(value))return WEBSITE+'/'+value;
    return value;
  }
  if(Array.isArray(value))return value.map(sitePaths);
  if(value&&typeof value==='object')return Object.fromEntries(Object.entries(value).map(([key,item])=>[key,sitePaths(item)]));
  return value;
}
const errorResponse=(message,status=503)=>new Response(JSON.stringify({error:message}),{status,headers:{'Content-Type':'application/json; charset=utf-8','Cache-Control':'private, no-store','X-Content-Type-Options':'nosniff'}});
async function proxy(request){
  try{
    const url=new URL(request.url),path='/api/'+url.pathname.slice(API_PREFIX.length)+url.search,tokens=await readTokens();
    const headers=new Headers();
    for(const name of ['Content-Type','X-CSRF','X-Upload-Consent','Idempotency-Key','Range','If-Range','Accept'])if(request.headers.has(name))headers.set(name,request.headers.get(name));

    if(tokens.customer)headers.set(TOKEN_HEADERS.customer,tokens.customer);

    const init={method:request.method,headers,mode:'cors',credentials:'omit',cache:'no-store',redirect:'error',signal:request.signal};
    if(!['GET','HEAD'].includes(request.method))init.body=await request.arrayBuffer();
    const response=await fetch(BACKEND+path,init);
    const expired=response.status===401&&url.pathname===API_PREFIX+'health';
    await updateTokens(response.headers,tokens.demo,{clear:expired});
    const outputHeaders=new Headers(response.headers);
    for(const name of [...Object.values(TOKEN_HEADERS),'Set-Cookie','WWW-Authenticate','Content-Length','Content-Encoding','Access-Control-Allow-Origin','Access-Control-Allow-Credentials'])outputHeaders.delete(name);
    outputHeaders.set('Cache-Control','private, no-store');outputHeaders.set('X-Content-Type-Options','nosniff');
    let body=response.body;
    if(request.method==='HEAD'||[204,205,304].includes(response.status))body=null;
    else if((response.headers.get('content-type')||'').includes('application/json'))body=JSON.stringify(sitePaths(await response.json()));
    return new Response(body,{status:response.status,statusText:response.statusText,headers:outputHeaders});
  }catch{return errorResponse('The demo service is temporarily unavailable. Please try again.');}
}
self.addEventListener('install',event=>event.waitUntil(self.skipWaiting()));
self.addEventListener('activate',event=>event.waitUntil((async()=>{const tokens=await readTokens();const headers=new Headers({'X-LHF-Customer-Session':tokens.customer||''});await updateTokens(headers,tokens.demo,{clear:true});await self.clients.claim();})()));
self.addEventListener('message',event=>{if(event.data?.type==='LHF_PAGES_CLAIM')event.waitUntil(self.clients.claim());});
self.addEventListener('fetch',event=>{
  const url=new URL(event.request.url);
  if(url.origin===self.location.origin&&url.pathname.startsWith(API_PREFIX))event.respondWith(proxy(event.request));
});
