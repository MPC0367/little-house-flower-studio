  const S = LHF.data.strings, until = LHF.data.policies.priceValidUntil;
  const fill = (lang) => LHF.i18n.fmtDate(until, 'long', lang);
  /* custom.budget.hint quotes this period's posted range (250.– to 2,690.–), so it goes quiet with the prices */
