export function t(key,vars){
  const entry=S[key];
  let text=entry?entry[current==='th'?1:0]:key;
  if(vars)text=text.replace(/\{(\w+)\}/g,(m,name)=>vars[name]!=null?String(vars[name]):m);
  return text;
}
