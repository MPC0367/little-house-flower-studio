/* Every word the Studio shows, in English and Thai. The Thai is written for the shop's own staff,
   not translated word for word; status words are the shop's own (the ones in its Google Sheet).
   t('key', {name:value}) fills {name}. The choice is kept per device (lhf.admin.language.v1, the
   key the earlier Studio used, so nobody loses their setting). */
const KEY='lhf.admin.language.v1';
let current='en';
try{const saved=localStorage.getItem(KEY);current=saved==='th'||saved==='en'?saved:(navigator.language||'').toLowerCase().startsWith('th')?'th':'en';}catch{current=(navigator.language||'').toLowerCase().startsWith('th')?'th':'en';}
document.documentElement.lang=current;
export const lang=()=>current;
export function setLang(value){
  current=value==='th'?'th':'en';
  try{localStorage.setItem(KEY,current);}catch{}
  document.documentElement.lang=current;
  window.dispatchEvent(new CustomEvent('lhf:languagechange',{detail:current}));
}

